const footer = new Footer({ children: [new Paragraph({ alignment: AlignmentType.RIGHT, children: [new TextRun({ children: [PageNumber.CURRENT], font: FONT, bold: true, size: 32 })] })] });
function save(children, file) {
  const doc = new Document({
    styles: { default: { document: { run: { font: FONT, size: 21 } } } },
    sections: [{ properties: { page: { size: { width: 11906, height: 16838 }, margin: { top: 1134, right: 1134, bottom: 1134, left: 1134 } } }, footers: { default: footer }, children }],
  });
  return Packer.toBuffer(doc).then((b) => fs.writeFileSync(file, b));
}

