function utilitySection(num, title, intro, stages) {
  const out = [];
  out.push(H1(title));
  out.push(P(intro));
  out.push(Q(`${num}-1  아래 6개 단계마다, 가장 아쉬운 점을 하나만 골라 주세요.`));
  out.push(note('각 행에서 하나만 선택합니다. 해당 단계를 경험하지 않았으면 N/A를 선택합니다.'));
  out.push(table([{ w: 1200, align: C }, { w: 8438 }], ['보기', '의미'], LEVERS.map((l) => [l[0], l[1]]).concat([['N/A', '경험 없음·판단 어려움']])));
  out.push(spacer());
  const w = Math.floor((9638 - 567 - 3007) / 8);
  const cols = [{ w: 567, align: C }, { w: 3007 }, ...Array(8).fill({ w, align: C })];
  out.push(table(cols, ['번호', '단계와 예시', 'A', 'B', 'C', 'D', 'E', 'F', 'G', 'N/A'],
    stages.map((s, i) => [String(i + 1), [s[0], s[1]], ...Array(8).fill('□')])));
  out.push(spacer());
  out.push(Q(`${num}-2  ${num}-1에서 A~F를 고른 단계만, 그 아쉬움이 얼마나 큰지 표시해 주세요.`));
  out.push(note('1 매우 작음  2 작음  3 보통  4 큼  5 매우 큼.  G나 N/A를 고른 단계는 비워 둡니다.'));
  out.push(grid(stages.map((s) => s[0]), false, '단계'));
  return out;
}

