// ---------- helpers ----------
const run = (t, o = {}) => new TextRun({ text: t, font: FONT, bold: !!o.bold, size: o.size || 21, color: o.color || '000000', italics: !!o.italics });
const P = (t, o = {}) => new Paragraph({
  children: Array.isArray(t) ? t : [run(t, o)],
  spacing: { before: o.before || 0, after: o.after ?? 120, line: 264 },
  keepNext: !!o.keepNext, alignment: o.align,
});
const Q = (t) => P(t, { bold: true, keepNext: true, before: 120 });
const note = (t) => P(t, { size: 18, color: '555555', keepNext: true });
const H1 = (t, pb = true) => new Paragraph({ children: [run(t, { bold: true, size: 32 })], spacing: { before: 240, after: 120 }, keepNext: true, pageBreakBefore: pb });
const H2 = (t) => new Paragraph({ children: [run(t, { bold: true, size: 26 })], spacing: { before: 200, after: 100 }, keepNext: true });
const TITLE = (t) => new Paragraph({ children: [run(t, { bold: true, size: 42 })], spacing: { after: 120 } });
const box = (items) => items.map((i) => '□ ' + i).join('   ');

const B = { style: BorderStyle.SINGLE, size: 4, color: 'D9D9D9' };
const borders = { top: B, bottom: B, left: B, right: B };
function cell(text, w, o = {}) {
  const paras = (Array.isArray(text) ? text : [text]).map((t, i) => new Paragraph({
    children: [run(t, { bold: o.bold || (o.head && true), size: o.size || (i > 0 ? 18 : 19), color: i > 0 ? '555555' : '000000' })],
    alignment: o.align || AlignmentType.LEFT, spacing: { after: 0, line: 240 }, keepNext: !o.last,
  }));
  return new TableCell({
    children: paras, width: { size: w, type: WidthType.DXA }, borders,
    verticalAlign: VerticalAlign.CENTER,
    margins: { top: 50, bottom: 50, left: 80, right: 80 },
    shading: o.head ? { type: ShadingType.CLEAR, color: 'auto', fill: 'E8EDF2' } : undefined,
  });
}
// cols: [{w, align}] ; header: array ; rows: array of arrays
function table(cols, header, rows) {
  const total = cols.reduce((a, c) => a + c.w, 0);
  const mk = (r, head) => new TableRow({
    cantSplit: true, tableHeader: head, height: { value: head ? 397 : 340, rule: 'atLeast' },
    children: r.map((t, i) => cell(t, cols[i].w, { head, last: r.__last, align: head ? AlignmentType.CENTER : cols[i].align })),
  });
  return new Table({
    width: { size: total, type: WidthType.DXA }, columnWidths: cols.map((c) => c.w),
    alignment: AlignmentType.CENTER,
    rows: [mk(header, true), ...rows.map((r, i) => { if (i === rows.length - 1) r.__last = true; return mk(r, false); })],
  });
}
const C = AlignmentType.CENTER;
const spacer = () => P('', { after: 60 });

// rating grid: targets x (1..5, N/A)
function grid(targets, withNA = true, label = '비교 대상') {
  const n = withNA ? 6 : 5;
  const w = Math.floor((9638 - 567 - 2835) / n);
  const cols = [{ w: 567, align: C }, { w: 2835 }, ...Array(n).fill({ w, align: C })];
  const head = ['번호', label, '1', '2', '3', '4', '5', ...(withNA ? ['N/A'] : [])];
  return table(cols, head, targets.map((t, i) => [String(i + 1), t, ...Array(n).fill('□')]));
}
// importance table
function importance(factors) {
  const cols = [{ w: 567, align: C }, { w: 4819 }, ...Array(5).fill({ w: 850, align: C })];
  return table(cols, ['번호', '선택 기준과 의미', '1', '2', '3', '4', '5'],
    factors.map((f, i) => [String(i + 1), [f[0], f[1]], '□', '□', '□', '□', '□']));
}
// experience code table
function expTable(targets, codes) {
  const w = Math.floor((9638 - 567 - 2835) / codes.length);
  const cols = [{ w: 567, align: C }, { w: 2835 }, ...codes.map(() => ({ w, align: C }))];
  return table(cols, ['번호', '비교 대상', ...codes], targets.map((t, i) => [String(i + 1), t, ...codes.map(() => '□')]));
}

