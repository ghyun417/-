// ---------- helpers ----------
const run = (t, o = {}) => new TextRun({ text: t, font: FONT, bold: !!o.bold, size: o.size || 21, color: o.color || '000000' });
const P = (t, o = {}) => new Paragraph({
  children: [run(t, o)], spacing: { before: o.before || 0, after: o.after ?? 120, line: 264 }, keepNext: !!o.keepNext,
});
const Q = (t) => P(t, { bold: true, keepNext: true, before: 120 });
const note = (t) => P(t, { size: 18, color: '555555', keepNext: true });
const H1 = (t) => new Paragraph({ children: [run(t, { bold: true, size: 32 })], spacing: { before: 240, after: 120 }, keepNext: true, pageBreakBefore: true });
const H2 = (t) => new Paragraph({ children: [run(t, { bold: true, size: 26 })], spacing: { before: 200, after: 100 }, keepNext: true });
